const fs = require('fs'), os = require('os'), path = require('path'), crypto = require('crypto');
const { chromium, devices } = require('playwright');
const ext = path.resolve(process.argv[2]);
const id = crypto.createHash('sha256').update(ext).digest('hex').slice(0, 32).split('').map((c) => String.fromCharCode(97 + parseInt(c, 16))).join('');
const VER = JSON.parse(fs.readFileSync(path.join(ext, 'manifest.json'), 'utf8')).version;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0, n = 0;
const check = (name, got, want) => { n++; const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fails++; console.log((ok ? 'ok   ' : 'FAIL ') + name + (ok ? '' : '\n       got  ' + JSON.stringify(got) + '\n       want ' + JSON.stringify(want))); };
const B = 'https://forum.ls-project.com';
const fake = (ver) => `<!doctype html><html><head><title>Kadr</title></head><body><article class="cPost"><div data-role="commentContent"><p>Шапка темы</p><a class="ipsAttachLink" data-fileext="zip" href="#">kadr-themes-lsforum-v${ver}.zip</a></div></article><article class="cPost"><div data-role="commentContent"><a href="#">kadr-themes-lsforum-v99.0.0.zip</a></div></article></body></html>`;
const login = () => { const d = document.createElement('div'); d.id = 'elUserLink_menu'; d.hidden = true; d.innerHTML = '<a href="https://forum.ls-project.com/index.php?/profile/1-tester/">me</a>'; document.body.appendChild(d); };
(async () => {
  const ctx = await chromium.launchPersistentContext(fs.mkdtempSync(path.join(os.tmpdir(), 'kadr-uc-')), { channel: 'chromium', headless: true, viewport: { width: 412, height: 860 }, isMobile: true, hasTouch: true, userAgent: devices['Pixel 7'].userAgent, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`] });
  let hits = 0, serve = '9.9.9';
  await ctx.route(/\/index\.php\?\/topic\/924-/, (r) => { if (!r.request().isNavigationRequest()) hits++; r.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: fake(serve) }); });
  const ctl = await ctx.newPage(); await ctl.goto(`chrome-extension://${id}/popup.html`);
  const get = (k) => ctl.evaluate((k) => new Promise((r) => chrome.storage.local.get(k, (d) => r(d[k]))), k);
  const badge = () => ctl.evaluate(() => new Promise((r) => chrome.action.getBadgeText({}, r)));
  await ctl.evaluate(() => new Promise((r) => chrome.storage.local.clear(() => chrome.storage.local.set({ theme: 'mint', skin: true }, r))));
  const page = await ctx.newPage();
  await page.goto(B + '/', { waitUntil: 'load', timeout: 60000 }); await sleep(4500);
  check('гость: тему 924 не запрашивает', hits, 0);
  check('гость: версия не записана', await get('updLatest'), undefined);
  await page.reload({ waitUntil: 'load' }); await page.evaluate(login); await sleep(4500);
  check('в аккаунте: один запрос к теме 924', hits, 1);
  check('версия взята из шапки (первый пост), а не из ответов', await get('updLatest'), '9.9.9');
  check('точка обновления на кнопке «Тема»', await page.evaluate(() => { const li = document.querySelector('[data-kadr-entry]'); return !!li && li.hasAttribute('data-kadr-upd') && getComputedStyle(li.querySelector('a'), '::after').content !== 'none'; }), true);
  check('значок на иконке расширения', await badge(), '1');
  await page.reload({ waitUntil: 'load' }); await page.evaluate(login); await sleep(4500);
  check('повторно в те же сутки не запрашивает', hits, 1);
  const pop = await ctx.newPage(); await pop.setViewportSize({ width: 380, height: 860 });
  await pop.goto(`chrome-extension://${id}/popup.html`); await sleep(500);
  check('попап: плашка с версией', await pop.evaluate(() => !document.getElementById('upd').hidden && document.getElementById('updTitle').textContent), 'Вышла версия 9.9.9');
  check('попап: ссылка ведёт в тему 924', await pop.evaluate(() => document.getElementById('updBtn').href), 'https://forum.ls-project.com/index.php?/topic/924-x/');
  check('попап: версия внизу', await pop.evaluate(() => document.getElementById('ver').textContent), 'Kadr ' + VER);
  await pop.close();
  const entry = page.locator('[data-kadr-entry] a');
  await entry.tap(); await sleep(1500);
  const fr = page.frames().find((f) => f.url().includes('popup.html#sheet'));
  check('шторка: плашка с версией видна', fr ? await fr.evaluate(() => !document.getElementById('upd').hidden) : 'no frame', true);
  if (fr) {
    await fr.click('#updBtn'); await sleep(2500);
    check('шторка: «Скачать» открывает тему в этой же вкладке', /topic\/924-/.test(page.url()), true);
    check('шторка закрылась', await page.evaluate(() => !document.querySelector('kadr-sheet')), true);
  }
  await page.evaluate(login); await sleep(4000);
  check('на странице темы 924 версия читается со страницы, без запроса', hits, 1);
  serve = VER;
  await ctl.evaluate(() => new Promise((r) => chrome.storage.local.set({ updAt: 0 }, r)));
  await page.goto(B + '/', { waitUntil: 'load' }); await page.evaluate(login); await sleep(4500);
  check('прошли сутки: запрос повторился', hits, 2);
  check('в шапке текущая версия: обновления нет', await get('updLatest'), VER);
  check('точки нет', await page.evaluate(() => document.querySelector('[data-kadr-entry]').hasAttribute('data-kadr-upd')), false);
  check('значка нет', await badge(), '');
  await ctx.close();
  console.log(`update-check: ${n} checks, ${fails} failures`);
})().catch((e) => { console.error(e); process.exit(2); });
