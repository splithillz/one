const { chromium } = require('playwright');
const path = require('path');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0, n = 0;
const check = (name, got, want) => { n++; const ok = got === want; if (!ok) fails++; console.log((ok ? 'ok   ' : 'FAIL ') + name + (ok ? '' : `\n       got  ${JSON.stringify(got)}\n       want ${JSON.stringify(want)}`)); };
(async () => {
  const b = await chromium.launch();
  const page = await b.newPage();
  await page.goto('file://' + path.resolve(process.argv[2] || path.join(__dirname, '..', 'demo.html')));
  const input = page.locator('#msg');
  const val = () => input.inputValue();
  const typeIt = async (s) => { await input.pressSequentially(s, { delay: 45 }); };
  const reset = async () => { await input.fill(''); await sleep(100); };
  await typeIt('здраствуйте '); await sleep(2500);
  check('опечатка исправляется после пробела', await val(), 'здравствуйте ');
  await page.keyboard.press('Backspace'); await sleep(200);
  check('Backspace сразу после исправления возвращает как было', await val(), 'здраствуйте ');
  await typeIt('и снова здраствуйте '); await sleep(900);
  check('отменённое слово больше не трогается', await val(), 'здраствуйте и снова здраствуйте ');
  await reset();
  await typeIt('/me досал телефон'); await sleep(900); await page.keyboard.press('Enter'); await sleep(300);
  check('команда не трогается, текст после неё — да', (await page.evaluate(() => window.sent || [])).pop(), '/me достал телефон');
  await reset();
  await typeIt('как дела харашо'); await sleep(900); await page.keyboard.press('Enter'); await sleep(300);
  check('последнее слово исправляется по Enter', (await page.evaluate(() => window.sent || [])).pop(), 'как дела хорошо');
  await reset();
  await typeIt('привет Джонн как жизнь ok 123 lol '); await sleep(900);
  check('имя с большой буквы, латиница и цифры не трогаются', await val(), 'привет Джонн как жизнь ok 123 lol ');
  await reset();
  await typeIt('Вайнвуд и лспд рядом '); await sleep(900);
  check('слова из списка сервера не трогаются', await val(), 'Вайнвуд и лспд рядом ');
  await reset();
  await typeIt('Сегодня я пошол домой. Потом спать '); await sleep(1100);
  check('несколько ошибок в одной фразе, регистр сохраняется', ['Сегодня я пошел домой. Потом спать ', 'Сегодня я пошёл домой. Потом спать '].includes(await val()) ? 'ok' : await val(), 'ok');
  await reset();
  await typeIt('кто-нибуть знает '); await sleep(1200);
  check('слово через дефис', await val(), 'кто-нибудь знает ');
  await reset();
  await typeIt('СИГОДНЯ '); await sleep(1200);
  check('КАПС сохраняется', await val(), 'СЕГОДНЯ ');
  await reset();
  await typeIt('ну короче вобщем '); await sleep(900);
  check('слитное «вобщем» → «в общем»', await val(), 'ну короче в общем ');
  await reset();
  await input.pressSequentially('я пошол домой и сказл привет ', { delay: 15 }); await sleep(1500);
  check('быстрый набор: исправлены все слова, а не только последнее', ['я пошел домой и сказал привет ', 'я пошёл домой и сказал привет '].includes(await val()) ? 'ok' : await val(), 'ok');
  await reset();
  await typeIt('лол спс норм кек здр ща '); await sleep(1200);
  check('сленг и короткие слова не трогаются', await val(), 'лол спс норм кек здр ща ');
  let calls = 0;
  page.on('request', (r) => { if (/speller\.yandex\.net/.test(r.url())) calls++; });
  await page.reload(); await sleep(500);
  await input.pressSequentially('здраствуйте как дела харашо ', { delay: 45 }); await sleep(1500);
  check('после перезагрузки слова берутся из памяти, без запросов', calls, 0);
  check('отменённое слово помнится после перезагрузки, остальное исправляется', await input.inputValue(), 'здраствуйте как дела хорошо ');
  await b.close();
  console.log(`autocorrect: ${n} checks, ${fails} failures`);
})().catch((e) => { console.error(e); process.exit(2); });
